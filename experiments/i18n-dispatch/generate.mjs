// Controlled local variants of yuku-ast 0.18.0. These are experiments, not public APIs.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { CHILD_KEYS } from '../../node_modules/yuku-ast/dist/generated.js';
const source = readFileSync(new URL('../../node_modules/yuku-ast/dist/walk.js', import.meta.url), 'utf8');
const contextSource = readFileSync(new URL('../../node_modules/yuku-ast/dist/context.js', import.meta.url), 'utf8');
const prefix = `// Generated by ../generate.mjs from the installed, pinned yuku-ast source.\n// Only the benchmark's synchronous Literal handler contract is supported.\nimport { ALIAS_GROUPS } from '../../../node_modules/yuku-ast/dist/aliases.js';\nimport { WalkContext } from '../../../node_modules/yuku-ast/dist/context.js';\nimport { CHILD_KEYS } from '../../../node_modules/yuku-ast/dist/generated.js';\n`;
const dispatchOriginal = source.slice(source.indexOf('function createDispatch'), source.indexOf('/**'));
const helpers = source.slice(source.indexOf('function position('), source.indexOf('export function _walk('));
const walkOriginal = source.slice(source.indexOf('export function _walk('), source.indexOf('// line-for-line twin'));
function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) throw new Error(`Patch is not unique: ${before.slice(0, 90)}`);
  return source.replace(before, after);
}
function childStep(key, context, exitChecks = true) {
 const callItem = context ? `visit(item, ${JSON.stringify(key)}, value, childFrame)` : 'visit(item)';
 const callValue = context ? `visit(value, ${JSON.stringify(key)}, null, null)` : 'visit(value)';
 const call = text => exitChecks ? `if (!${text}) return false;` : `${text};`;
 const loop = context ? 'const childFrame = { i: 0 };\nfor (; childFrame.i < value.length; childFrame.i++) {\nconst item = value[childFrame.i];' : 'for (let i = 0; i < value.length; i++) {\nconst item = value[i];';
 return `{ const value = node.${key};\nif (value !== null && value !== undefined && typeof value === 'object') {\nif (Array.isArray(value)) {\n${loop}\nif (item !== null) { ${call(callItem)} }\n}\n} else { ${call(callValue)} }\n}\n}`;
}
function directChildren(context) {
 return 'const children = Object.create(null);\n' + Object.entries(CHILD_KEYS).filter(([,keys])=>keys.length).map(([type, keys])=>`children[${JSON.stringify(type)}] = function children${type}(node, visit) {\n${keys.map(k=>childStep(k, context)).join('\n')}\nreturn true;\n};`).join('\n');
}
const variants=[];
for (const direct of [false,true]) for (const flat of [false,true]) for (const context of [true,false]) {
 const id=`yuku-${direct?'direct':'keys'}-${flat?'flat':'hooks'}-${context?'context':'readonly'}`;
 let dispatch=dispatchOriginal, walk=walkOriginal;
 if(flat) {
  dispatch=dispatch.replace('entry = { enter: [], leave: [] };','entry = { enter: null, leave: null };').replace('entry.enter.push(hooks.enter);','entry.enter = hooks.enter;').replace('entry.leave.unshift(hooks.leave);','entry.leave = hooks.leave;');
  for(const phase of ['enter','leave']) {
   const block=`if (typed !== undefined) {\n            for (const handler of typed.${phase}) {\n                handler(node, ctx);\n                if (ctx._stopped)\n                    return false;\n            }\n        }`;
   walk=replaceOnce(walk,block,`if (typed !== undefined && typed.${phase} !== null) {\n            typed.${phase}(node, ctx);\n            if (ctx._stopped) return false;\n        }`);
  }
 }
 if(direct) {
  const begin=walk.indexOf('            const keys = CHILD_KEYS[node.type];');
  const end=walk.indexOf('\n        }\n        position(ctx',begin);
  if(begin<0||end<0)throw new Error('Child loop not found');
  walk=walk.slice(0,begin)+`            const childWalker = children[node.type];\n            if (childWalker !== undefined) {\n                ancestors.push(node);\n                if (!childWalker(node, visit)) return false;\n                ancestors.pop();\n            }`+walk.slice(end);
 }
 if(!context) {
  walk=walk.replace('ctx.state = state;\n    const ancestors = ctx._ancestors;','');
  walk=walk.replace('const parent = ctx.parent;','').replaceAll('position(ctx, node, key, list, frame);','');
  walk=walk.replace(/\s*if \(ctx\._stopped\)\s*return false;/g,'');
  const begin=walk.indexOf('        if (ctx._removed) {'),end=walk.indexOf('        if (!skipped) {',begin);
  if(begin<0||end<0)throw new Error('Mutation checks not found');
  walk=walk.slice(0,begin)+'        {\n'+walk.slice(end+'        if (!skipped) {\n'.length);
  const tail='        if (ctx._removed)\n            applyRemove(ctx, parent, key, list, frame);\n        else if (ctx._replacement !== null)\n            applyReplace(ctx, parent, key, list, frame);';
  walk=replaceOnce(walk,tail,'');
  walk=walk.replaceAll('ancestors.push(node);','').replaceAll('ancestors.pop();','');
  walk=walk.replaceAll('(node, ctx)','(node)');
  walk=walk.replace('function visit(node, key, list, frame)','function visit(node)');
  walk=walk.replace('const childFrame = { i: 0 };\n                        for (; childFrame.i < value.length; childFrame.i++) {\n                            const item = value[childFrame.i];','for (let i = 0; i < value.length; i++) {\n                            const item = value[i];');
  walk=walk.replace('visit(item, key2, value, childFrame)','visit(item)').replace('visit(value, key2, null, null)','visit(value)').replace('})(root, null, null, null);','})(root);');
 }
 const entry=`export function walk(root, visitors, state) {\n  _walk(root, visitors, state${context?', new WalkContext()':''});\n  return root;\n}\n`;
 const code=prefix+dispatch+(context?helpers:'')+(direct?directChildren(context):'')+'\n'+entry+walk;
 writeFileSync(new URL(`./generated/${id}.mjs`,import.meta.url),code);
 variants.push({id,direct,flat,context});
}
// Same child coverage/order as Yuku, but Acorn's handler replacement mechanism.
const acornBase='export const base = Object.create(null);\n'+Object.entries(CHILD_KEYS).map(([type,keys])=>`base[${JSON.stringify(type)}] = function children${type}(node, state, visit) {\n${keys.map(k=>childStep(k,false,false)).join('\n')}\n};`).join('\n');
writeFileSync(new URL('./generated/acorn-full-base.mjs',import.meta.url),acornBase);
const metadata={yukuVersion:'0.18.0',sourceSHA256:createHash('sha256').update(source).digest('hex'),contextSHA256:createHash('sha256').update(contextSource).digest('hex'),variants};
writeFileSync(new URL('./generated/manifest.json',import.meta.url),JSON.stringify(metadata,null,2)+'\n');
console.log(`Generated ${variants.length} factorial variants and full-coverage Acorn base.`);
